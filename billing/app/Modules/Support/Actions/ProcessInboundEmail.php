<?php

namespace App\Modules\Support\Actions;

use App\Events\Support\InboundEmailBounced;
use App\Events\Support\InboundEmailRejected;
use App\Modules\Support\Data\TicketAuthor;
use App\Modules\Support\Data\TicketDraft;
use App\Modules\Support\Drivers\Inbound\InboundMessage;
use App\Modules\Support\Enums\InboundEmailStatus;
use App\Modules\Support\Enums\TicketSource;
use App\Modules\Support\Enums\TicketStatus;
use App\Modules\Support\Models\Department;
use App\Modules\Support\Models\InboundEmail;
use App\Modules\Support\Models\SpamRule;
use App\Modules\Support\Models\Ticket;
use App\Modules\Support\Models\TicketMessage;
use App\Modules\Support\Services\AttachmentStore;
use App\Modules\Support\Services\IncomingFile;
use App\Modules\Support\Services\MessageWriter;
use App\Modules\Support\Services\QuoteStripper;
use App\Modules\Support\Services\RequesterResolver;
use App\Modules\Support\Services\SupportSettings;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Throwable;

/**
 * Inbound email pipeline (spec §6): dedupe → drop auto-generated/loops → per-sender rate limit →
 * spam rules → match ticket → authorise sender → reply/reopen or open a new ticket.
 * Every outcome is recorded on support_inbound_emails.
 */
class ProcessInboundEmail
{
    public const RATE_WINDOW_MINUTES = 15;

    private const BULK_PRECEDENCE = ['bulk', 'list', 'junk', 'auto_reply'];

    /** @var list<string> temp files written for attachments of the mail being processed */
    private array $temporaryFiles = [];

    public function __construct(
        private SupportSettings $settings,
        private RequesterResolver $requesters,
        private QuoteStripper $quotes,
        private AttachmentStore $attachments,
        private MessageWriter $messages,
        private OpenTicket $openTicket,
        private PostReply $postReply,
    ) {}

    /**
     * @param  array<string, mixed>  $payload  raw provider payload, kept for 30 days
     */
    public function handle(InboundMessage $mail, array $payload = []): InboundEmail
    {
        $key = $mail->dedupeKey();

        $record = InboundEmail::query()->createOrFirst(['message_id' => $key], [
            'provider' => $mail->provider,
            'from' => Str::limit($mail->fromEmail, 250, ''),
            'to' => Str::limit(implode(', ', $mail->recipients()), 250, ''),
            'subject' => Str::limit($mail->subject, 250, ''),
            'status' => InboundEmailStatus::Received,
            'received_at' => now(),
        ]);

        if (! $record->wasRecentlyCreated && $record->status !== InboundEmailStatus::Failed) {
            return $record;
        }

        try {
            if ($record->raw_path === null) {
                $record->forceFill(['raw_path' => $this->storeRaw($payload)])->save();
            }

            return $this->process($record, $mail);
        } catch (Throwable $exception) {
            // Keep the row so the provider's retry re-processes it instead of being treated as a duplicate.
            $record->forceFill(['status' => InboundEmailStatus::Failed, 'reason' => Str::limit($exception->getMessage(), 250, '')])->save();

            throw $exception;
        } finally {
            $this->discardTemporaryFiles();
        }
    }

    private function process(InboundEmail $record, InboundMessage $mail): InboundEmail
    {
        if (! filter_var($mail->fromEmail, FILTER_VALIDATE_EMAIL) && $mail->fromEmail !== '') {
            return $this->reject($record, 'invalid sender address', InboundEmailStatus::RejectedAutoSubmitted);
        }

        if ($reason = $this->autoGeneratedReason($mail)) {
            return $this->reject($record, $reason, InboundEmailStatus::RejectedAutoSubmitted);
        }

        if (Department::query()->whereRaw('lower(email) = ?', [$mail->fromEmail])->exists()) {
            return $this->reject($record, 'sender is a department address', InboundEmailStatus::RejectedLoop);
        }

        if ($mail->messageId !== null && TicketMessage::query()->where('email_message_id', $record->message_id)->exists()) {
            return $this->reject($record, 'Message-ID is one of our own outbound messages', InboundEmailStatus::RejectedLoop);
        }

        $recent = InboundEmail::query()->where('from', $record->from)->whereKeyNot($record->id)
            ->where('received_at', '>=', now()->subMinutes(self::RATE_WINDOW_MINUTES))->count();

        if ($recent >= $this->settings->int('inbound_max_per_sender', 10)) {
            return $this->reject($record, 'too many messages from sender', InboundEmailStatus::RejectedRateLimit);
        }

        $body = $this->quotes->strip($mail->text, $this->settings->string('reply_marker'));

        if (SpamRule::query()->get()->contains(fn (SpamRule $rule): bool => $rule->matches($mail->fromEmail, $mail->subject, $mail->text))) {
            return $this->reject($record, 'matched a spam rule', InboundEmailStatus::RejectedSpam);
        }

        [$ticket, $threaded] = $this->matchTicket($mail);

        return $ticket !== null
            ? $this->reply($record, $ticket, $mail, $body, $threaded)
            : $this->open($record, $mail, $body);
    }

    /**
     * Staff import of a blocked reply from the ticket view.
     */
    public function import(InboundEmail $record, InboundMessage $mail): TicketMessage
    {
        try {
            return $this->importBlocked($record, $mail);
        } finally {
            $this->discardTemporaryFiles();
        }
    }

    private function importBlocked(InboundEmail $record, InboundMessage $mail): TicketMessage
    {
        /** @var Ticket $ticket */
        $ticket = Ticket::query()->findOrFail($record->ticket_id)->resolveMergeTarget();
        [$files, $notes] = $this->files($mail);
        $isClient = $ticket->client_id !== null;

        $message = $this->postReply->handle(
            $ticket,
            TicketAuthor::emailSender($this->senderName($mail), $mail->fromEmail, $isClient),
            $this->quotes->strip($mail->text, $this->settings->string('reply_marker')) ?: '(empty message)',
            $files,
            source: TicketSource::Email,
            emailMessageId: $record->message_id,
            unverified: true,
        );

        foreach ($notes as $note) {
            $this->messages->systemNote($ticket, $note);
        }

        $record->forceFill(['status' => InboundEmailStatus::Imported, 'ticket_id' => $ticket->id])->save();

        return $message;
    }

    private function autoGeneratedReason(InboundMessage $mail): ?string
    {
        $autoSubmitted = strtolower(trim((string) $mail->header('auto-submitted')));

        if ($autoSubmitted !== '' && $autoSubmitted !== 'no') {
            return 'Auto-Submitted: '.$autoSubmitted;
        }

        if (in_array(strtolower(trim((string) $mail->header('precedence'))), self::BULK_PRECEDENCE, true)) {
            return 'Precedence: '.$mail->header('precedence');
        }

        foreach (['x-auto-response-suppress', 'x-autoreply', 'x-autorespond', 'list-id'] as $header) {
            if ($mail->header($header) !== null) {
                return $header;
            }
        }

        if (trim((string) $mail->header('return-path')) === '<>') {
            return 'empty Return-Path (bounce)';
        }

        if ($mail->fromEmail === '' || str_starts_with($mail->fromEmail, 'mailer-daemon@') || str_starts_with($mail->fromEmail, 'postmaster@')) {
            return 'null or mailer-daemon sender';
        }

        return null;
    }

    /**
     * The ticket a reply belongs to, and whether it was matched through our own unguessable
     * Message-IDs (In-Reply-To/References) rather than only the guessable [#number] subject token.
     *
     * @return array{0: Ticket|null, 1: bool}
     */
    private function matchTicket(InboundMessage $mail): array
    {
        $ids = array_values(array_filter([$mail->inReplyTo, ...$mail->references]));

        if ($ids !== []) {
            $ticketId = TicketMessage::query()->whereIn('email_message_id', $ids)->value('ticket_id');

            if ($ticketId !== null) {
                return [Ticket::query()->whereKey($ticketId)->first()?->resolveMergeTarget(), true];
            }
        }

        if (preg_match('/\[#([A-Za-z0-9-]{1,32})\]/', $mail->subject, $match) === 1) {
            return [Ticket::query()->where('number', $match[1])->first()?->resolveMergeTarget(), false];
        }

        return [null, false];
    }

    /**
     * A reply is trusted only when the sender is linked to the ticket AND the mail is either threaded on
     * one of our Message-IDs or passed SPF/DKIM/DMARC; the From header alone can be spoofed (spec §6.6).
     * Anything else is held back for staff (or imported with an "unverified sender" badge when allowed).
     */
    private function reply(InboundEmail $record, Ticket $ticket, InboundMessage $mail, string $body, bool $threaded): InboundEmail
    {
        $record->ticket_id = $ticket->id;
        $authorized = $this->requesters->isAuthorizedSender($ticket, $mail->fromEmail);
        $verified = $authorized && $mail->authenticated !== false && ($threaded || $mail->authenticated === true);
        $unverified = false;

        if (! $verified) {
            if (! $this->settings->bool('allow_unverified_email_replies')) {
                $reason = $authorized
                    ? 'sender could not be verified (no thread reference and no SPF/DKIM/DMARC pass)'
                    : 'sender is not linked to the ticket';
                $record->forceFill(['status' => InboundEmailStatus::Blocked, 'reason' => $reason])->save();
                InboundEmailRejected::dispatch($record->id, InboundEmailStatus::Blocked->value);

                return $record;
            }

            $unverified = true;
        }

        if ($ticket->status === TicketStatus::Closed && $this->settings->bool('prevent_email_reopen')) {
            return $this->bounce($record, InboundEmailStatus::BouncedClosed, 'ticket.closed_bounce', $mail->fromEmail);
        }

        [$files, $notes] = $this->files($mail);
        $match = $this->requesters->match($mail->fromEmail);
        $isClient = $ticket->client_id !== null && $match !== null && $match['client_id'] === $ticket->client_id;

        $this->postReply->handle(
            $ticket,
            TicketAuthor::emailSender($this->senderName($mail), $mail->fromEmail, $isClient, $isClient ? $match['contact_id'] : null),
            $body !== '' ? $body : '(empty message)',
            $files,
            source: TicketSource::Email,
            emailMessageId: $record->message_id,
            unverified: $unverified,
        );

        foreach ($notes as $note) {
            $this->messages->systemNote($ticket, $note);
        }

        if ($this->settings->bool('auto_add_cc')) {
            $this->addCc($ticket, $mail);
        }

        $record->forceFill(['status' => InboundEmailStatus::ReplyAdded])->save();

        return $record;
    }

    private function open(InboundEmail $record, InboundMessage $mail, string $body): InboundEmail
    {
        $department = $this->department($mail);

        if ($department === null) {
            return $this->reject($record, 'no department for recipient', InboundEmailStatus::RejectedNoDepartment);
        }

        if ($department->replies_only_by_email) {
            return $this->bounce($record, InboundEmailStatus::BouncedRepliesOnly, 'ticket.replies_only_bounce', $mail->fromEmail);
        }

        $match = $this->requesters->match($mail->fromEmail);

        if ($department->clients_only && $match === null) {
            return $this->bounce($record, InboundEmailStatus::BouncedUnregistered, 'ticket.unregistered_bounce', $mail->fromEmail);
        }

        [$files, $notes] = $this->files($mail);
        $name = $this->senderName($mail);

        $ticket = $this->openTicket->handle(new TicketDraft(
            departmentId: $department->id,
            subject: $mail->subject !== '' ? $mail->subject : '(no subject)',
            body: $body !== '' ? $body : '(empty message)',
            author: TicketAuthor::emailSender($name, $mail->fromEmail, $match !== null, $match['contact_id'] ?? null),
            requesterName: $name,
            requesterEmail: $mail->fromEmail,
            clientId: $match['client_id'] ?? null,
            contactId: $match['contact_id'] ?? null,
            source: TicketSource::Email,
            cc: $this->settings->bool('auto_add_cc') ? $this->ccFrom($mail) : [],
            files: $files,
            emailMessageId: $record->message_id,
            notes: $notes,
        ));

        $record->forceFill(['status' => InboundEmailStatus::TicketCreated, 'ticket_id' => $ticket->id])->save();

        return $record;
    }

    private function department(InboundMessage $mail): ?Department
    {
        $recipients = $mail->recipients();

        if ($recipients !== []) {
            $department = Department::query()->get()->first(fn (Department $department): bool => in_array(mb_strtolower($department->email), $recipients, true));

            if ($department !== null) {
                return $department;
            }
        }

        $default = $this->settings->int('default_department_id');

        return $default > 0 ? Department::query()->find($default) : null;
    }

    /**
     * Attachments that pass §4.3, plus system notes for the rejected ones.
     *
     * @return array{0: list<IncomingFile>, 1: list<string>}
     */
    private function files(InboundMessage $mail): array
    {
        $accepted = [];
        $rejected = [];

        foreach ($mail->attachments as $attachment) {
            if (count($accepted) >= $this->attachments->maxFiles()) {
                $rejected[] = $attachment['name'].': '.__('too many attachments');

                continue;
            }

            if (strlen($attachment['content']) > $this->attachments->maxBytes()) {
                $rejected[] = $attachment['name'].': '.__('Files may be at most :size MB.', ['size' => $this->settings->int('attachment_max_mb', 10)]);

                continue;
            }

            $file = IncomingFile::fromContents($attachment['name'], $attachment['content']);
            $this->temporaryFiles[] = $file->path;

            $reason = $this->attachments->rejectionReason($file, staff: false);

            if ($reason === null) {
                $accepted[] = $file;
            } else {
                $rejected[] = $attachment['name'].': '.$reason;
            }
        }

        $notes = $rejected === [] ? [] : [__('Attachments rejected from the inbound email:')."\n\n".implode("\n", array_map(fn (string $line): string => '- '.$line, $rejected))];

        return [$accepted, $notes];
    }

    /**
     * @return list<string>
     */
    private function ccFrom(InboundMessage $mail): array
    {
        $departments = Department::query()->pluck('email')->map(fn (string $email): string => mb_strtolower($email))->all();

        return array_slice(array_values(array_diff($mail->cc, $departments, [$mail->fromEmail])), 0, 10);
    }

    private function addCc(Ticket $ticket, InboundMessage $mail): void
    {
        $cc = array_values(array_unique([...($ticket->cc ?? []), ...$this->ccFrom($mail)]));
        $cc = array_values(array_diff($cc, [mb_strtolower($ticket->requester_email)]));

        if ($cc !== ($ticket->cc ?? [])) {
            $ticket->cc = array_slice($cc, 0, 10);
            $ticket->save();
        }
    }

    /**
     * Display name for the sender: the From display name, else the matching login or contact name.
     */
    private function senderName(InboundMessage $mail): string
    {
        if ($mail->fromName !== '') {
            return Str::limit($mail->fromName, 250, '');
        }

        return $this->requesters->nameFor($mail->fromEmail) ?? Str::before($mail->fromEmail, '@');
    }

    private function discardTemporaryFiles(): void
    {
        foreach ($this->temporaryFiles as $path) {
            if (is_file($path)) {
                @unlink($path);
            }
        }

        $this->temporaryFiles = [];
    }

    private function reject(InboundEmail $record, string $reason, InboundEmailStatus $status): InboundEmail
    {
        $record->forceFill(['status' => $status, 'reason' => $reason])->save();
        InboundEmailRejected::dispatch($record->id, $status->value);

        return $record;
    }

    private function bounce(InboundEmail $record, InboundEmailStatus $status, string $template, string $recipient): InboundEmail
    {
        $record->forceFill(['status' => $status, 'reason' => $template])->save();
        InboundEmailBounced::dispatch($record->id, $template, $recipient);

        return $record;
    }

    /**
     * @param  array<string, mixed>  $payload
     */
    private function storeRaw(array $payload): ?string
    {
        if ($payload === []) {
            return null;
        }

        $path = 'support/inbound/'.now()->format('Y/m/d').'/'.Str::uuid().'.json';
        Storage::disk(AttachmentStore::DISK)->put($path, (string) json_encode($payload), ['visibility' => 'private']);

        return $path;
    }
}
