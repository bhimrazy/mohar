<?php

namespace App\Modules\Core\Support;

use App\Support\Kernel;
use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use ReflectionClass;
use ReflectionClassConstant;
use ReflectionEnum;
use ReflectionEnumBackedCase;
use ReflectionMethod;
use ReflectionParameter;
use ReflectionProperty;
use UnitEnum;

/**
 * The public kernel surface as text, one self-contained line per class, constant, enum case, property and method
 * (ADR 0010 "Enforcement"), sorted so a diff names exactly what changed. Built by reflection over the kernel
 * directories only: every class in app/Contracts, app/Data, app/Events and app/Enums, and the app/Support classes
 * whose docblock carries `@api`. Members inherited from a parent or a trait are listed on the class that declares
 * them; private members, docblock types and payload shapes are not part of the snapshot.
 */
final class KernelApiSnapshot
{
    public const PATH = 'docs/architecture/kernel-api.txt';

    /** Directories whose every class is public (ADR 0010 "Public surface"). */
    private const PUBLIC_DIRECTORIES = ['Contracts', 'Data', 'Events', 'Enums'];

    /** Directory whose classes are public only with `@api`. */
    private const API_TAGGED_DIRECTORY = 'Support';

    /**
     * @param  string  $path  the committed snapshot file
     */
    public function __construct(private string $appPath, private string $namespace, public string $path) {}

    public static function forApp(): self
    {
        return new self(app_path(), 'App\\', base_path(self::PATH));
    }

    public function render(): string
    {
        $lines = [];

        foreach ($this->classes() as $class) {
            array_push($lines, ...$this->linesFor(new ReflectionClass($class)));
        }

        return "# Kernel API snapshot (ADR 0010). Generated by `php artisan kernel:api-snapshot`; do not edit by hand.\n"
            .'api '.Kernel::API_VERSION."\n\n"
            .implode("\n", $lines)."\n";
    }

    /**
     * The kernel classes, interfaces, traits and enums, sorted.
     *
     * @return list<class-string>
     */
    public function classes(): array
    {
        $classes = [];

        foreach ([...self::PUBLIC_DIRECTORIES, self::API_TAGGED_DIRECTORY] as $directory) {
            $root = $this->appPath.'/'.$directory;

            if (! is_dir($root)) {
                continue;
            }

            foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS)) as $file) {
                if ($file->getExtension() !== 'php') {
                    continue;
                }

                $relative = substr($file->getPathname(), strlen($this->appPath) + 1, -4);
                $class = $this->namespace.str_replace('/', '\\', $relative);

                if (! class_exists($class) && ! interface_exists($class) && ! trait_exists($class) && ! enum_exists($class)) {
                    continue;
                }

                if ($directory === self::API_TAGGED_DIRECTORY && preg_match('/^\s*\*\s*@api\b/m', (string) (new ReflectionClass($class))->getDocComment()) !== 1) {
                    continue;
                }

                $classes[] = $class;
            }
        }

        sort($classes);

        return $classes;
    }

    /**
     * @param  ReflectionClass<object>  $class
     * @return list<string>
     */
    private function linesFor(ReflectionClass $class): array
    {
        $name = $class->getName();
        $members = [];

        foreach ($class->getReflectionConstants() as $constant) {
            if ($constant->getDeclaringClass()->getName() === $name && ! $constant->isPrivate() && ! $constant->isEnumCase() && $this->visible($class, $constant)) {
                $members['1 '.$constant->getName()] = "{$name} const {$constant->getName()} = ".$this->value($constant->getValue());
            }
        }

        if ($class->isEnum()) {
            foreach ((new ReflectionEnum($name))->getCases() as $case) {
                $members['2 '.$case->getName()] = "{$name} case {$case->getName()}"
                    .($case instanceof ReflectionEnumBackedCase ? ' = '.var_export($case->getBackingValue(), true) : '');
            }
        }

        $traitProperties = $this->traitMembers($class, fn (ReflectionClass $trait): array => $trait->getProperties());

        // An enum's only properties are the built-in $name and $value.
        foreach ($class->isEnum() ? [] : $class->getProperties() as $property) {
            if ($property->getDeclaringClass()->getName() === $name && ! $property->isPrivate() && $this->visible($class, $property)
                && ! in_array($property->getName(), $traitProperties, true)) {
                $members['3 '.$property->getName()] = "{$name} property ".$this->property($property);
            }
        }

        foreach ($class->getMethods() as $method) {
            if ($method->getDeclaringClass()->getName() === $name && ! $method->isPrivate() && $this->visible($class, $method)
                && $method->getFileName() === $class->getFileName()) {
                $members['4 '.$method->getName()] = "{$name} method ".$this->method($class, $method);
            }
        }

        ksort($members);

        return [$this->header($class), ...array_values($members)];
    }

    /**
     * Protected members matter only to a class that can be extended.
     *
     * @param  ReflectionClass<object>  $class
     */
    private function visible(ReflectionClass $class, ReflectionClassConstant|ReflectionProperty|ReflectionMethod $member): bool
    {
        return $member->isPublic() || ! $class->isFinal();
    }

    /**
     * @param  ReflectionClass<object>  $class
     */
    private function header(ReflectionClass $class): string
    {
        $kind = match (true) {
            $class->isInterface() => 'interface',
            $class->isTrait() => 'trait',
            $class->isEnum() => 'enum'.(($backing = (new ReflectionEnum($class->getName()))->getBackingType()) !== null ? ': '.$backing : ''),
            default => implode(' ', array_filter([
                $class->isFinal() ? 'final' : null,
                $class->isAbstract() ? 'abstract' : null,
                $class->isReadOnly() ? 'readonly' : null,
                'class',
            ])),
        };

        $parent = $class->getParentClass();
        $interfaces = $class->isInterface() ? [] : $this->ownInterfaces($class);
        $doc = (string) $class->getDocComment();

        return implode(' ', array_filter([
            $class->getName(),
            $kind,
            $parent !== false ? 'extends '.$parent->getName() : null,
            $class->isInterface() && $class->getInterfaceNames() !== [] ? 'extends '.implode(', ', $this->sorted($class->getInterfaceNames())) : null,
            $interfaces !== [] ? 'implements '.implode(', ', $interfaces) : null,
            $class->getTraitNames() !== [] ? 'uses '.implode(', ', $this->sorted($class->getTraitNames())) : null,
            preg_match('/^\s*\*\s*@open\b/m', $doc) === 1 ? '@open' : null,
            preg_match('/^\s*\*\s*@deprecated\b/m', $doc) === 1 ? '@deprecated' : null,
        ]));
    }

    /**
     * Interfaces the class names itself, not those its parent already implements; enums' built-in ones are left out.
     *
     * @param  ReflectionClass<object>  $class
     * @return list<string>
     */
    private function ownInterfaces(ReflectionClass $class): array
    {
        $parent = $class->getParentClass();
        $inherited = $parent !== false ? $parent->getInterfaceNames() : [];
        $builtIn = $class->isEnum() ? [UnitEnum::class, \BackedEnum::class] : [];

        return $this->sorted(array_diff($class->getInterfaceNames(), $inherited, $builtIn));
    }

    private function property(ReflectionProperty $property): string
    {
        return implode(' ', array_filter([
            $property->isPublic() ? 'public' : 'protected',
            $property->isStatic() ? 'static' : null,
            $property->isReadOnly() ? 'readonly' : null,
            $property->hasType() ? (string) $property->getType() : null,
            '$'.$property->getName(),
        ]));
    }

    /**
     * @param  ReflectionClass<object>  $class
     */
    private function method(ReflectionClass $class, ReflectionMethod $method): string
    {
        $modifiers = $class->isInterface() ? [] : array_filter([
            $method->isPublic() ? 'public' : 'protected',
            $method->isAbstract() ? 'abstract' : null,
            $method->isFinal() && ! $class->isFinal() ? 'final' : null,
        ]);

        if ($method->isStatic()) {
            $modifiers[] = 'static';
        }

        $parameters = implode(', ', array_map($this->parameter(...), $method->getParameters()));
        $return = $method->hasReturnType() ? ': '.$method->getReturnType() : '';
        $deprecated = preg_match('/^\s*\*\s*@deprecated\b/m', (string) $method->getDocComment()) === 1 ? ' @deprecated' : '';

        return implode(' ', [...$modifiers, ($method->returnsReference() ? '&' : '').$method->getName()."({$parameters}){$return}{$deprecated}"]);
    }

    private function parameter(ReflectionParameter $parameter): string
    {
        $text = ($parameter->hasType() ? $parameter->getType().' ' : '')
            .($parameter->isPassedByReference() ? '&' : '')
            .($parameter->isVariadic() ? '...' : '')
            .'$'.$parameter->getName();

        if (! $parameter->isDefaultValueAvailable()) {
            return $text;
        }

        return $text.' = '.($parameter->isDefaultValueConstant() ? (string) $parameter->getDefaultValueConstantName() : $this->value($parameter->getDefaultValue()));
    }

    private function value(mixed $value): string
    {
        return match (true) {
            $value === null => 'null',
            $value instanceof UnitEnum => $value::class.'::'.$value->name,
            is_object($value) => 'new '.$value::class,
            is_array($value) => (string) json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
            default => var_export($value, true),
        };
    }

    /**
     * Names of the members the class's traits declare (properties carry no file name to tell them apart).
     *
     * @param  ReflectionClass<object>  $class
     * @param  callable(ReflectionClass<object>): list<ReflectionProperty>  $members
     * @return list<string>
     */
    private function traitMembers(ReflectionClass $class, callable $members): array
    {
        $names = [];

        foreach ($class->getTraits() as $trait) {
            foreach ($members($trait) as $member) {
                $names[] = $member->getName();
            }
        }

        return $names;
    }

    /**
     * @param  array<array-key, string>  $names
     * @return list<string>
     */
    private function sorted(array $names): array
    {
        $names = array_values($names);
        sort($names);

        return $names;
    }
}
